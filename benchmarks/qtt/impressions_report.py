"""benchmarks/qtt/impressions_report.py -- the U08 go/no-go table from first_impressions.jl's CSVs.

usage: python impressions_report.py INDIR OUT.md

Plan §1.2A decision rule, applied per (fixture, L, chi, bond, tol_basis): an arm is ACCURACY-MATCHED
when its median time-weighted miss fits the share (miss_tw_med <= share) and it has no false
accepts; the randomized hybrid (D3 / D3warm) is KEPT for that regime only when it is at least 20 %
cheaper in CBE wall time than the best accuracy-matched deterministic (D0) or fixed-width (D2_l)
control. Otherwise: size-aware deterministic / fixed-width fallback.
"""
import csv, sys, math
from collections import defaultdict


def f(x):
    try:
        return float(x)
    except ValueError:
        return math.nan


def main(indir, out):
    R = list(csv.DictReader(open(f"{indir}/qtt_cbe_nosym_ablation.csv")))
    D = list(csv.DictReader(open(f"{indir}/dims.csv")))
    groups = defaultdict(list)
    for r in R:
        groups[(r["fixture"], r["L"], r["chi_target"], r["bond"], r["tag"], r["tol_basis"])].append(r)
    lines = ["# No-symmetry DD-CBE first impressions (QTT plan §1.2A, U08)", "",
             f"Source: `{indir}/qtt_cbe_nosym_ablation.csv` (generated by `benchmarks/qtt/first_impressions.jl`).", "",
             "## DD dimensions (actual, every bond)", "",
             "| fixture | L | chi target | bonds | median n_L^D | max n_L^D | median n_R^D | max n_R^D | max chi |",
             "|---|---|---|---|---|---|---|---|---|"]
    dg = defaultdict(list)
    for d in D:
        dg[(d["fixture"], d["L"], d["chi_target"])].append(d)
    for k, ds in sorted(dg.items()):
        nl = sorted(int(d["nL"]) for d in ds); nr = sorted(int(d["nR"]) for d in ds)
        lines.append(f"| {k[0]} | {k[1]} | {k[2]} | {len(ds)} | {nl[len(nl)//2]} | {nl[-1]} | "
                     f"{nr[len(nr)//2]} | {nr[-1]} | {max(int(d['chi']) for d in ds)} |")
    lines += ["", "## Arms per local problem", "",
              "| fixture | L | chi | bond | tol | m | n | trivial | arm | branch | cols | dirs | rho_L med | miss_tw/share | false acc | t [ms] |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    keep, fall, triv = 0, 0, 0
    decisions = []
    for k, rs in sorted(groups.items()):
        share = f(rs[0]["share"])
        for r in rs:
            lines.append(f"| {k[0]} | {k[1]} | {r['chi_true']} | {k[3]} {k[4]} | {k[5]} | {r['m']} | {r['n']} | "
                         f"{r['trivial']} | {r['arm']} | {r['branch']} | {f(r['cols_med']):.0f} | {f(r['dirs_med']):.0f} | "
                         f"{f(r['rhoL_med']):.2e} | {f(r['miss_tw_med'])/share:.2f} | {r['false_accepts']} | "
                         f"{1e3*f(r['t_med']):.2f} |")
        if rs[0]["trivial"] == "true":
            triv += 1
            decisions.append((k, "trivial (||A_DD|| ~ 0): not interpreted"))
            continue
        ok = [r for r in rs if f(r["miss_tw_med"]) <= share and int(r["false_accepts"]) == 0]
        ctrl = [r for r in ok if r["arm"] == "D0" or r["arm"].startswith("D2")]
        hyb = [r for r in ok if r["arm"] in ("D3", "D3warm")]
        if not hyb:
            fall += 1
            decisions.append((k, "fallback: no accuracy-matched D3"))
            continue
        hb = min(hyb, key=lambda r: f(r["t_med"]))
        if not ctrl:
            keep += 1
            decisions.append((k, f"keep {hb['arm']} (no accuracy-matched control)"))
            continue
        cb = min(ctrl, key=lambda r: f(r["t_med"]))
        gain = 1 - f(hb["t_med"]) / f(cb["t_med"])
        if gain >= 0.2:
            keep += 1
            decisions.append((k, f"keep {hb['arm']}: {100*gain:.0f}% cheaper than {cb['arm']}"))
        else:
            fall += 1
            decisions.append((k, f"fallback to {cb['arm']}: D3 gain {100*gain:.0f}% < 20%"))
    lines += ["", "## Go / no-go per regime", "", "| regime | decision |", "|---|---|"]
    for k, d in decisions:
        lines.append(f"| {k[0]} L{k[1]} chi{k[2]} bond {k[3]} ({k[4]}) tol {k[5]} | {d} |")
    lines += ["", f"**Totals:** randomized hybrid kept in {keep} regimes, deterministic/fixed fallback in "
                  f"{fall}, trivial {triv}.", ""]
    S = list(csv.DictReader(open(f"{indir}/steps.csv")))
    lines += ["## Full-step loops (with and without CBE)", "",
              "| fixture | arm | steps | total wall [s] | mean f_CBE | mean f_rho | final err vs ref | max chi |",
              "|---|---|---|---|---|---|---|---|"]
    sg = defaultdict(list)
    for s in S:
        sg[(s["fixture"], s["arm"])].append(s)
    for k, ss in sorted(sg.items()):
        lines.append(f"| {k[0]} | {k[1]} | {len(ss)} | {sum(f(s['wall']) for s in ss):.1f} | "
                     f"{sum(f(s['f_cbe']) for s in ss)/len(ss):.3f} | {sum(f(s['f_rho']) for s in ss)/len(ss):.3f} | "
                     f"{f(ss[-1].get('err_vs_ref', 'nan')):.2e} | {max(int(float(s['chi_max'])) for s in ss)} |")
    lines += ["", "Amdahl bound: a 2x CBE speedup gives at most 1/(1 - f_CBE/2) on the whole step.", ""]
    open(out, "w").write("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
